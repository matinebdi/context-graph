"""Per-project installers that wire the context graph into an AI client.

Each installer merges its entries into the client's own config files (never clobbering other
servers or hooks) and is idempotent: running it twice gives the same result, and `uninstall`
removes exactly what `install` added.
"""

from __future__ import annotations

import json
import shutil
import sys
from importlib import resources
from pathlib import Path

from .model import GraphError

SERVER_NAME = "context-graph"
REPO = "matinebdi/context-graph"
GIT_SOURCE = f"git+https://github.com/{REPO}#subdirectory=plugins/context-graph"
HOOK_MARKER = "hook session-start"


def agent_instructions() -> str:
    return resources.files("context_graph").joinpath("assets/agent-instructions.md").read_text(encoding="utf-8")


def interpreter() -> str:
    """Absolute path of the Python that runs this package, used to launch the server and hook as
    `python -m context_graph.<module>`. That works where generated console-script .exe launchers
    are blocked (e.g. Windows Smart App Control) and doesn't depend on the client's PATH."""
    exe = Path(sys.executable).resolve()
    if any(part in {"archive-v0", "builds-v0"} for part in exe.parts):
        raise GraphError(
            "this is a temporary uvx environment, which uv may delete later. Install the package "
            "first and rerun the command from it:\n"
            f'  uv tool install "{GIT_SOURCE}"\n'
            "  context-graph install <client>"
        )
    return str(exe)


def _load_json(path: Path, default: dict) -> dict:
    if not path.exists():
        return default
    text = path.read_text(encoding="utf-8").strip()
    if not text:
        return default
    try:
        data = json.loads(text)
    except json.JSONDecodeError as e:
        raise GraphError(f"{path} is not valid JSON ({e}); fix or remove it, then retry") from e
    if not isinstance(data, dict):
        raise GraphError(f"{path} does not contain a JSON object")
    return data


def _write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def _shell_path(path: str) -> str:
    """A path usable in a hook command whichever shell runs it (bash, cmd or PowerShell):
    forward slashes, quoted only when it contains spaces."""
    path = Path(path).as_posix()
    return f'"{path}"' if " " in path else path


# ---------------------------------------------------------------- Cursor

CURSOR_RULE = """---
description: Long-term memory via the context-graph MCP server (Neo4j knowledge graph)
alwaysApply: true
---

<!-- Generated by `context-graph install cursor`; rerun it to update. -->

"""


def _is_our_cursor_hook(entry: dict) -> bool:
    cmd = entry.get("command", "") if isinstance(entry, dict) else ""
    return "context_graph" in cmd and HOOK_MARKER in cmd


def install_cursor(project: Path) -> list[str]:
    project = project.resolve()
    cursor = project / ".cursor"
    python = interpreter()

    mcp_path = cursor / "mcp.json"
    mcp = _load_json(mcp_path, {})
    mcp.setdefault("mcpServers", {})[SERVER_NAME] = {
        "type": "stdio",
        "command": python,
        "args": ["-m", "context_graph.server"],
        "env": {"CONTEXT_GRAPH_PROJECT_DIR": "${workspaceFolder}"},
    }
    _write_json(mcp_path, mcp)

    hooks_path = cursor / "hooks.json"
    hooks = _load_json(hooks_path, {"version": 1, "hooks": {}})
    hooks.setdefault("version", 1)
    starts = [h for h in hooks.setdefault("hooks", {}).get("sessionStart", []) if not _is_our_cursor_hook(h)]
    starts.append({"command": f"{_shell_path(python)} -m context_graph.cli {HOOK_MARKER} --format cursor"})
    hooks["hooks"]["sessionStart"] = starts
    _write_json(hooks_path, hooks)

    rule_path = cursor / "rules" / "context-graph.mdc"
    rule_path.parent.mkdir(parents=True, exist_ok=True)
    rule_path.write_text(CURSOR_RULE + agent_instructions(), encoding="utf-8")

    return [str(p.relative_to(project)) for p in (mcp_path, hooks_path, rule_path)]


def uninstall_cursor(project: Path) -> list[str]:
    project = project.resolve()
    cursor = project / ".cursor"
    changed = []

    mcp_path = cursor / "mcp.json"
    mcp = _load_json(mcp_path, {})
    if SERVER_NAME in mcp.get("mcpServers", {}):
        del mcp["mcpServers"][SERVER_NAME]
        _write_json(mcp_path, mcp)
        changed.append(mcp_path)

    hooks_path = cursor / "hooks.json"
    hooks = _load_json(hooks_path, {})
    starts = hooks.get("hooks", {}).get("sessionStart")
    if starts is not None:
        kept = [h for h in starts if not _is_our_cursor_hook(h)]
        if len(kept) != len(starts):
            if kept:
                hooks["hooks"]["sessionStart"] = kept
            else:
                del hooks["hooks"]["sessionStart"]
            _write_json(hooks_path, hooks)
            changed.append(hooks_path)

    rule_path = cursor / "rules" / "context-graph.mdc"
    if rule_path.exists():
        rule_path.unlink()
        changed.append(rule_path)
    return [str(p.relative_to(project)) for p in changed]


