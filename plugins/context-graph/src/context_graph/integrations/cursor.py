from pathlib import Path

from context_graph.integrations.base import ClientIntegration, JsonConfig, PythonRuntime


class CursorIntegration(ClientIntegration):
    """Cursor: MCP server, ``sessionStart`` and ``stop`` hooks, and an always-on rule in ``.cursor/``.

    Attributes:
        mcp_config: ``.cursor/mcp.json``.
        hooks_config: ``.cursor/hooks.json``.
        rule_file: ``.cursor/rules/context-graph.mdc``.
    """

    NAME = "cursor"
    SERVER = "context-graph"
    HOOK_MARKER = "context_graph.cli hook "
    # Cursor hook event -> our hook event.
    HOOK_EVENTS = {"sessionStart": "session-start", "stop": "stop"}
    RULE_HEADER = (
        "---\n"
        "description: Long-term memory via the context-graph MCP server (Neo4j knowledge graph)\n"
        "alwaysApply: true\n"
        "---\n\n"
        "<!-- Generated by `context-graph install cursor`; rerun it to update. -->\n\n"
    )

    def __init__(self, project: Path):
        super().__init__(project)
        cursor = self.project / ".cursor"
        self.mcp_config = JsonConfig(cursor / "mcp.json")
        self.hooks_config = JsonConfig(cursor / "hooks.json")
        self.rule_file = cursor / "rules" / "context-graph.mdc"

    def install(self) -> list[Path]:
        python = PythonRuntime.interpreter()

        mcp = self.mcp_config.load({})
        mcp.setdefault("mcpServers", {})[self.SERVER] = {
            "type": "stdio",
            "command": python,
            "args": ["-m", "context_graph.server"],
            "env": {"CONTEXT_GRAPH_PROJECT_DIR": "${workspaceFolder}", "CONTEXT_GRAPH_CLIENT": "cursor"},
        }
        self.mcp_config.save(mcp)

        hooks = self.hooks_config.load({"version": 1, "hooks": {}})
        hooks.setdefault("version", 1)
        events = hooks.setdefault("hooks", {})
        for cursor_event, our_event in self.HOOK_EVENTS.items():
            entries = [h for h in events.get(cursor_event, []) if not self._is_ours(h)]
            command = f"{PythonRuntime.shell_path(python)} -m {self.HOOK_MARKER}{our_event} --format cursor"
            entries.append({"command": command})
            events[cursor_event] = entries
        self.hooks_config.save(hooks)

        self.rule_file.parent.mkdir(parents=True, exist_ok=True)
        self.rule_file.write_text(self.RULE_HEADER + self.agent_instructions(), encoding="utf-8")
        return [self.mcp_config.path, self.hooks_config.path, self.rule_file]

    def uninstall(self) -> list[Path]:
        changed = []

        mcp = self.mcp_config.load({})
        if self.SERVER in mcp.get("mcpServers", {}):
            del mcp["mcpServers"][self.SERVER]
            self.mcp_config.save(mcp)
            changed.append(self.mcp_config.path)

        hooks = self.hooks_config.load({})
        events = hooks.get("hooks", {})
        removed = False
        for cursor_event in self.HOOK_EVENTS:
            entries = events.get(cursor_event)
            if entries is None:
                continue
            kept = [h for h in entries if not self._is_ours(h)]
            if len(kept) != len(entries):
                removed = True
                if kept:
                    events[cursor_event] = kept
                else:
                    del events[cursor_event]
        if removed:
            self.hooks_config.save(hooks)
            changed.append(self.hooks_config.path)

        if self.rule_file.exists():
            self.rule_file.unlink()
            changed.append(self.rule_file)
        return changed

    def next_steps(self) -> str:
        return (
            "  1. context-graph up        (once per machine: starts the local Neo4j in Docker)\n"
            "  2. Restart Cursor, then enable the `context-graph` server under Settings -> MCP if asked.\n"
            "  3. The paths written in .cursor/ are specific to this machine: each teammate runs\n"
            "     `context-graph install cursor` themselves instead of sharing those files."
        )

    @classmethod
    def _is_ours(cls, hook: dict) -> bool:
        return isinstance(hook, dict) and cls.HOOK_MARKER in hook.get("command", "")
